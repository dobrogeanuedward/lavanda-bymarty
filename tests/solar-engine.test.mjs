import test from 'node:test';
import assert from 'node:assert/strict';
import * as Astronomy from 'astronomy-engine';
import { AU_KM, SOLAR_FRAME, SOLAR_DATE_RANGE, SOLAR_BODIES, SolarError, computeSolarSystem, sampleOrbit, sampleOrbitAsync } from '../src/solar-engine.js';

const options = { engine: Astronomy };
const epoch = '2026-10-16T00:00:00Z';
const norm = vector => Math.hypot(...vector);
const difference = (a, b) => a.map((value, index) => value - b[index]);
const closeVector = (actual, expected, tolerance, label = '') => assert.ok(norm(difference(actual, expected)) <= tolerance, `${label}: error ${norm(difference(actual, expected))} AU exceeds ${tolerance}`);
const byKey = state => new Map(state.bodies.map(body => [body.key, body]));
const code = expected => error => error instanceof SolarError && error.code === expected;

// Independent JPL Horizons API fixtures retrieved 2026-10-16, not generated by AE.
// https://ssd-api.jpl.nasa.gov/doc/horizons.html
// VECTORS, REF_PLANE=ECLIPTIC, REF_SYSTEM=ICRF, VEC_CORR=NONE, OUT_UNITS=AU-D,
// TIME_TYPE=UT. Bodies 399/199/599/899 relative to 500@10; Moon301 to 500@399.
// These are UTC instants; the first is not the exact J2000 epoch defined in TT.
const HORIZONS = [
  { date: '2000-01-01T12:00:00Z', positions: {
    earth: [-0.1771478822733411, 0.9672393401210591, -0.000004085203551709195],
    mercury: [-0.1300777328324658, -0.4472924077888585, -0.02460015509549487],
    jupiter: [4.001174041917682, 2.938580568964424, -0.1017852273047504],
    neptune: [16.81204952165866, -24.99176193299895, 0.1272224403813134],
  }, moon: [-0.001949005522028226, -0.001838439640328155, 0.0002424530340027334], sunBarycentric: [-0.007137175166112787, -0.002796002997935671, 0.000206298436106503] },
  { date: epoch, positions: {
    earth: [0.922652300410749, 0.3779822757539222, -0.00002600195297887477],
    mercury: [0.2823281869327146, -0.3068526380248863, -0.05097137405840625],
    jupiter: [-3.576313968972209, 3.926971485628895, 0.06370257559768079],
    neptune: [29.83496501749852, 1.427431302084502, -0.7169340832160165],
  }, moon: [-0.0003181218384477595, -0.002673571245259812, -0.0002168643737496738], sunBarycentric: [-0.001154871853884386, -0.005101897252804462, 0.00009272251467064768] },
];
// AE is a compact approximate model; these tolerances cover its observed errors
// with margin and do not represent the much smaller uncertainty of Horizons.
const TOLERANCE_AU = { earth: 3e-5, mercury: 2e-5, jupiter: 4e-4, neptune: 5e-3, moon: 1.5e-7 };

test('ten immutable bodies use volumetric mean radii, traceable periods and exact AU conversion', () => {
  assert.equal(SOLAR_BODIES.length, 10);
  assert.deepEqual(SOLAR_BODIES.map(body => body.key), ['sun', 'mercury', 'venus', 'earth', 'mars', 'jupiter', 'saturn', 'uranus', 'neptune', 'moon']);
  assert.equal(AU_KM, 149597870.7);
  assert.equal(SOLAR_FRAME, 'J2000 ecliptic');
  assert.ok(Object.isFrozen(SOLAR_BODIES));
  for (const body of SOLAR_BODIES) {
    assert.ok(Object.isFrozen(body));
    assert.ok(Number.isFinite(body.radiusKm) && body.radiusKm > 0);
    assert.match(body.color, /^#[a-f0-9]{6}$/i);
    assert.ok(body.summary.length > 70);
    assert.match(body.sourceUrl, /^https:\/\/(ssd\.jpl\.nasa\.gov|nssdc\.gsfc\.nasa\.gov)\//);
  }
  assert.equal(SOLAR_BODIES.find(body => body.key === 'earth').radiusKm, 6371.0084);
  assert.equal(SOLAR_BODIES.find(body => body.key === 'jupiter').radiusKm, 69911);
  assert.equal(SOLAR_BODIES.find(body => body.key === 'moon').orbitalPeriodDays, 27.3217);
  assert.equal(SOLAR_BODIES.find(body => body.key === 'neptune').orbitalPeriodDays, 164.79132 * 365.25);
  assert.equal(SOLAR_BODIES[0].orbitalPeriodDays, null, 'the Sun is not assigned a planetary period');
});

for (const fixture of HORIZONS) test(`geometric J2000 ecliptic coordinates match independent JPL Horizons at ${fixture.date}`, () => {
  const state = computeSolarSystem(fixture.date, options), bodies = byKey(state);
  for (const [key, expected] of Object.entries(fixture.positions)) {
    closeVector(bodies.get(key).position, expected, TOLERANCE_AU[key], key);
    const actual = bodies.get(key).position;
    const cosine = actual.reduce((sum, value, index) => sum + value * expected[index], 0) / (norm(actual) * norm(expected));
    const arcminutes = Math.acos(Math.max(-1, Math.min(1, cosine))) * 180 / Math.PI * 60;
    assert.ok(arcminutes < 1, `${key}: ${arcminutes} arcminutes`);
  }
  closeVector(state.moonGeocentric, fixture.moon, TOLERANCE_AU.moon, 'Moon relative to Earth');
  // Sun target10 relative to SSB 500@0. Angular errors are unsuitable near origin.
  closeVector(state.sunBarycentric, fixture.sunBarycentric, 1.5e-5, 'Sun relative to SSB');
});

test('heliocentric, geocentric and barycentric positions are coherent at a single instant', () => {
  const state = computeSolarSystem(epoch, options), bodies = byKey(state);
  assert.equal(state.date, '2026-10-16T00:00:00.000Z');
  assert.deepEqual(bodies.get('sun').position, [0, 0, 0]);
  assert.equal(bodies.get('sun').distanceSunAU, 0);
  assert.equal(bodies.get('earth').distanceEarthAU, 0);
  closeVector(difference(bodies.get('moon').position, bodies.get('earth').position), state.moonGeocentric, 1e-15);
  assert.ok(Math.abs(bodies.get('moon').distanceEarthAU - norm(state.moonGeocentric)) < 1e-15);
  assert.equal(bodies.get('sun').distanceEarthAU, bodies.get('earth').distanceSunAU);
  assert.ok(norm(state.sunBarycentric) > 0.001 && norm(state.sunBarycentric) < 0.02);
  for (const body of state.bodies) {
    assert.ok(body.position.every(Number.isFinite));
    closeVector(difference(body.barycentricPosition, body.position), state.sunBarycentric, 3e-15, body.key);
    assert.equal(body.distanceSunAU, norm(body.position));
  }
  closeVector(bodies.get('sun').barycentricPosition, state.sunBarycentric, 0);
});

test('Earth distance changes across perihelion and aphelion rather than following a circle', () => {
  const january = byKey(computeSolarSystem('2026-01-03T12:00:00Z', options)).get('earth').distanceSunAU;
  const july = byKey(computeSolarSystem('2026-07-06T12:00:00Z', options)).get('earth').distanceSunAU;
  assert.ok(january > 0.982 && january < 0.985);
  assert.ok(july > 1.015 && july < 1.018);
  assert.ok(july - january > 0.03);
});

test('sampled Mercury preserves eccentricity, inclination and unequal travel in equal times', () => {
  const orbit = sampleOrbit('mercury', epoch, { ...options, samples: 192 });
  const radii = orbit.points.map(norm);
  assert.ok(Math.min(...radii) > 0.30 && Math.min(...radii) < 0.32);
  assert.ok(Math.max(...radii) > 0.46 && Math.max(...radii) < 0.48);
  assert.ok(Math.max(...radii) - Math.min(...radii) > 0.15);
  assert.ok(orbit.points.some(point => Math.abs(point[2]) > 0.04));
  const steps = orbit.points.slice(1).map((point, index) => norm(difference(point, orbit.points[index])));
  assert.ok(Math.max(...steps) / Math.min(...steps) > 1.4);
});

test('trajectory dates include true endpoints and center, without forcing a closed ellipse', () => {
  const orbit = sampleOrbit('mars', epoch, { ...options, samples: 32 });
  assert.equal(orbit.points.length, 33);
  assert.equal(orbit.origin, 'sun');
  assert.equal(orbit.frame, SOLAR_FRAME);
  assert.equal(orbit.closed, false);
  assert.ok(Math.abs((new Date(orbit.centerDate) - new Date(orbit.startDate)) - (new Date(orbit.endDate) - new Date(orbit.centerDate))) <= 1, 'Date serialization can round a fractional millisecond');
  closeVector(orbit.points[0], byKey(computeSolarSystem(orbit.startDate, options)).get('mars').position, 0);
  closeVector(orbit.points[16], byKey(computeSolarSystem(orbit.centerDate, options)).get('mars').position, 1e-10);
  closeVector(orbit.points[32], byKey(computeSolarSystem(orbit.endDate, options)).get('mars').position, 0);
  assert.ok(norm(difference(orbit.points[0], orbit.points.at(-1))) > 1e-5, 'endpoints retain actual perturbed positions');
});

test('local lunar samples stay geocentric while the main Moon position is heliocentric', () => {
  const orbit = sampleOrbit('moon', epoch, { ...options, samples: 32 }), state = computeSolarSystem(epoch, options);
  assert.equal(orbit.origin, 'earth');
  assert.equal(orbit.periodDays, 27.3217);
  closeVector(orbit.points[16], state.moonGeocentric, 1e-10);
  assert.ok(orbit.points.every(point => norm(point) > 0.0022 && norm(point) < 0.0029));
  assert.ok(byKey(state).get('moon').distanceSunAU > 0.9);
  assert.ok(orbit.points.some(point => Math.abs(point[2]) > 0.0001));
});

test('outer trajectories can extend beyond the selectable epoch range', () => {
  for (const date of [SOLAR_DATE_RANGE.min, SOLAR_DATE_RANGE.max]) {
    const orbit = sampleOrbit('neptune', date, { ...options, samples: 32 });
    assert.ok(new Date(orbit.startDate).getUTCFullYear() >= 1700);
    assert.ok(new Date(orbit.endDate).getUTCFullYear() <= 2300);
    assert.ok(orbit.points.every(point => point.every(Number.isFinite) && norm(point) > 29 && norm(point) < 31));
  }
  const futureTrack = sampleOrbit('neptune', SOLAR_DATE_RANGE.max, { ...options, samples: 16 });
  assert.ok(new Date(futureTrack.endDate).getUTCFullYear() > 2100);
  assert.throws(() => computeSolarSystem(futureTrack.endDate, options), code('DATE_OUT_OF_RANGE'));
});

test('the solar track is a twelve-year barycentric interval without inventing a solar orbital period', () => {
  const orbit = sampleOrbit('sun', epoch, { ...options, samples: 32 }), state = computeSolarSystem(epoch, options);
  assert.equal(orbit.origin, 'ssb');
  assert.equal(orbit.intervalLabel, 'Traiettoria del Sole su 12 anni');
  assert.equal(orbit.periodDays, 12 * 365.25);
  assert.equal(new Date(orbit.endDate) - new Date(orbit.startDate), 12 * 365.25 * 86400000);
  assert.equal(SOLAR_BODIES[0].orbitalPeriodDays, null);
  assert.equal(orbit.closed, false);
  closeVector(orbit.points[16], state.sunBarycentric, 0);
  assert.ok(orbit.points.every(point => norm(point) < 0.02));
  assert.ok(norm(difference(orbit.points[0], orbit.points.at(-1))) > 0.001);
  assert.ok(orbit.points.some(point => norm(difference(point, state.sunBarycentric)) > 0.005));
});

test('rotation axes are unit vectors in the same fixed ecliptic frame and meridians stay normalized', () => {
  const state = computeSolarSystem(epoch, options), bodies = byKey(state);
  for (const body of state.bodies) {
    assert.ok(Math.abs(norm(body.rotation.north) - 1) < 1e-12);
    assert.ok(body.rotation.primeMeridianDegrees >= 0 && body.rotation.primeMeridianDegrees < 360);
  }
  const earthTilt = Math.acos(bodies.get('earth').rotation.north[2]) * 180 / Math.PI;
  assert.ok(earthTilt > 23 && earthTilt < 24);
  assert.ok(Math.abs(bodies.get('uranus').rotation.north[2]) < 0.2, 'Uranus pole is nearly in the ecliptic plane');
  const noAxis = { ...Astronomy, RotationAxis: undefined };
  assert.ok(computeSolarSystem(epoch, { engine: noAxis }).bodies.every(body => !('rotation' in body)));
});

test('explicit timezone, timestamps and Dates agree without mutating caller data', () => {
  const date = new Date(epoch), before = date.getTime();
  const expected = computeSolarSystem(date, options);
  assert.deepEqual(computeSolarSystem(before, options), expected);
  assert.deepEqual(computeSolarSystem('2026-10-16T02:00:00+02:00', options), expected);
  assert.equal(date.getTime(), before);
  expected.bodies[0].position[0] = 999;
  expected.bodies[0].rotation.north[0] = 999;
  assert.equal(computeSolarSystem(date, options).bodies[0].position[0], 0);
  assert.ok(computeSolarSystem(date, options).bodies[0].rotation.north[0] < 1);
});

test('invalid dates, bodies, sampling counts and missing engines fail explicitly', () => {
  for (const date of [null, undefined, '', '2026-10-16', '2026-10-16T12:00:00', Number.NaN, Infinity, -Infinity, new Date(Number.NaN), {}, '2026-99-99T12:00:00Z', '2026-02-30T12:00:00Z', '2026-02-29T12:00:00+02:00', '1900-02-29T12:00:00Z', '2026-04-31T12:00:00Z', '2026-04-30T24:00:00Z']) assert.throws(() => computeSolarSystem(date, options), code('INVALID_DATE'));
  assert.equal(computeSolarSystem('2000-02-29T12:00:00Z', options).date, '2000-02-29T12:00:00.000Z');
  for (const date of ['1899-12-31T23:59:59Z', '2101-01-01T00:00:00Z']) assert.throws(() => computeSolarSystem(date, options), code('DATE_OUT_OF_RANGE'));
  assert.throws(() => computeSolarSystem(epoch, { engine: {} }), code('MISSING_ENGINE'));
  assert.throws(() => sampleOrbit('pluto', epoch, options), code('INVALID_BODY'));
  for (const samples of [0, 15, 2049, 20.5, Number.NaN, Infinity, '192']) assert.throws(() => sampleOrbit('earth', epoch, { ...options, samples }), code('INVALID_SAMPLES'));
  assert.throws(() => computeSolarSystem(epoch, { engine: { ...Astronomy, RotateVector: () => ({ x: Infinity, y: 0, z: 0 }) } }), code('INVALID_EPHEMERIS'));
});

test('async sampling yields to other work and returns identical geometric data', async () => {
  let yielded = false;
  setTimeout(() => { yielded = true; }, 0);
  for (const key of ['mercury', 'moon', 'sun']) {
    const asyncOrbit = await sampleOrbitAsync(key, epoch, { ...options, samples: 32, chunkSize: 8 });
    assert.deepEqual(asyncOrbit, sampleOrbit(key, epoch, { ...options, samples: 32 }));
  }
  assert.equal(yielded, true);
});

test('async trajectories can be cancelled before work and between chunks', async () => {
  const cancelled = new AbortController();
  cancelled.abort();
  await assert.rejects(sampleOrbitAsync('earth', epoch, { ...options, signal: cancelled.signal }), { name: 'AbortError' });
  let calls = 0;
  const counting = { ...Astronomy, HelioVector: (...args) => { calls++; return Astronomy.HelioVector(...args); } };
  const active = new AbortController();
  const pending = sampleOrbitAsync('earth', epoch, { engine: counting, samples: 192, chunkSize: 8, signal: active.signal });
  setTimeout(() => active.abort(), 0);
  await assert.rejects(pending, { name: 'AbortError' });
  assert.ok(calls > 0 && calls < 193);
  for (const chunkSize of [0, 257, 2.5, '24']) await assert.rejects(sampleOrbitAsync('moon', epoch, { ...options, chunkSize }), code('INVALID_CHUNK_SIZE'));
});
